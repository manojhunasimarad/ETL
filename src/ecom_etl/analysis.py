"""Step 6: run the business questions in ``sql/analysis`` against the star schema.

Each ``.sql`` file starts with two comment lines: the question (``-- Q1. ...``)
and the SQL technique it practises (``-- Technique: ...``). The runner
fills in the schema name, runs every file and writes a markdown report.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from decimal import Decimal
from importlib import resources
from typing import List, Optional

from .db import DbSettings, connect, schema_name


@dataclass
class Analysis:
    name: str
    question: str
    technique: str
    sql: str
    columns: List[str] = field(default_factory=list)
    rows: List[tuple] = field(default_factory=list)


def load_analyses(source: str) -> List[Analysis]:
    folder = resources.files("ecom_etl").joinpath("sql", "analysis")
    out = []
    for entry in sorted(folder.iterdir(), key=lambda p: p.name):
        if not entry.name.endswith(".sql"):
            continue
        text = entry.read_text(encoding="utf-8")
        lines = text.splitlines()
        question = lines[0].removeprefix("--").strip()
        technique = lines[1].removeprefix("--").strip().removeprefix("Technique:").strip()
        sql = text.replace("{gold}", schema_name(source, "gold"))
        out.append(Analysis(entry.name.removesuffix(".sql"), question, technique, sql))
    return out


def run_analyses(source: str, settings: Optional[DbSettings] = None) -> List[Analysis]:
    analyses = load_analyses(source)
    with connect(settings) as conn:
        for a in analyses:
            cur = conn.execute(a.sql)
            a.columns = [d.name for d in cur.description]
            a.rows = cur.fetchall()
    return analyses


def _fmt(value) -> str:
    if isinstance(value, Decimal):
        return f"{value:,}"
    if isinstance(value, int) and not isinstance(value, bool):
        return f"{value:,}"
    return "" if value is None else str(value)


def render_markdown(source: str, analyses: List[Analysis], max_rows: int = 12) -> str:
    out = [f"# Business questions: `{source}`", "",
           "Generated by `python -m ecom_etl analyze`. SQL in `src/ecom_etl/sql/analysis/`.", ""]
    for a in analyses:
        out += [f"## {a.question}", "", f"*{a.technique}* (`{a.name}.sql`)", "",
                "| " + " | ".join(a.columns) + " |", "|" + "---|" * len(a.columns)]
        out += ["| " + " | ".join(_fmt(v) for v in row) + " |" for row in a.rows[:max_rows]]
        if len(a.rows) > max_rows:
            out.append(f"\n{len(a.rows) - max_rows} more rows not shown.")
        out.append("")
    return "\n".join(out)
